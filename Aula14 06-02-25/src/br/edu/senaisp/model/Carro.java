package br.edu.senaisp.model;

public class Carro {

	public Carro(String nome, String marca, float km, String cor, String placa, String nomeCliente) {
		this.nome = nome;
		this.marca = marca;
		this.km = km;
		this.cor = cor;
		this.placa = placa;
		this.nomeCliente = nomeCliente;
	}

	public String nome;
	String marca;
	float km;
	String cor;
	String placa;
	String nomeCliente;

}
